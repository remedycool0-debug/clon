import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const referencePath = path.join(
  projectRoot,
  'public',
  'investor-pages',
  'check-out-your-investment-professional.html',
);
const sourceDir = path.join(projectRoot, 'recursos', 'sidebar-pages');
const manifestPath = path.join(projectRoot, 'recursos', 'sidebar-pages.json');
const generatedMapPath = path.join(projectRoot, 'lib', 'investor-sidebar-pages.generated.ts');
const investorOrigin = 'https://www.investor.gov';

function cleanText(value) {
  return value
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#039;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}

function linksFrom(section) {
  return [...section.matchAll(/<a\s+[^>]*href="([^"]+)"[^>]*>(.*?)<\/a>/gis)].map(
    ([, route, label]) => ({ route: route.replace(/&amp;/g, '&'), label: cleanText(label) }),
  );
}

function fileNameFor(route) {
  const digest = createHash('sha1').update(route).digest('hex').slice(0, 10);
  const lastSegment = route.split('/').filter(Boolean).at(-1) ?? 'page';
  const safeSegment = lastSegment.replace(/[^a-z0-9-]+/gi, '-').slice(0, 56);
  return `sidebar-${digest}-${safeSegment}`;
}

const html = await readFile(referencePath, 'utf8');
const menuStart = html.lastIndexOf('<ul class="menu" id="investor-main-menu">');
const menuEnd = html.indexOf('</nav>', menuStart);

if (menuStart < 0 || menuEnd < 0) {
  throw new Error('Could not locate the sidebar menu in the downloaded Investor.gov HTML.');
}

const sidebar = html.slice(menuStart, menuEnd);
const investingStart = sidebar.indexOf('<span>Investing Basics</span>');
const generalStart = sidebar.indexOf('<span>General Resources</span>');

if (investingStart < 0 || generalStart < 0) {
  throw new Error('Could not locate Investing Basics and General Resources in the sidebar.');
}

const investingLinks = linksFrom(sidebar.slice(investingStart, generalStart)).map((link) => ({
  ...link,
  section: 'Investing Basics',
}));
const generalLinks = linksFrom(sidebar.slice(generalStart)).map((link) => ({
  ...link,
  section: 'General Resources',
}));
const uniqueLinks = [...new Map([...investingLinks, ...generalLinks].map((link) => [link.route, link])).values()];
const manifest = uniqueLinks.map((link) => ({ ...link, file: fileNameFor(link.route) }));

await mkdir(sourceDir, { recursive: true });

const concurrency = 6;
let nextIndex = 0;

async function worker() {
  while (nextIndex < manifest.length) {
    const index = nextIndex++;
    const page = manifest[index];
    const response = await fetch(new URL(page.route, investorOrigin), {
      headers: { 'user-agent': 'Mozilla/5.0 local-reference-clone' },
    });

    if (!response.ok) {
      throw new Error(`${response.status} ${response.statusText}: ${page.route}`);
    }

    await writeFile(path.join(sourceDir, `${page.file}.html`), await response.text(), 'utf8');
    process.stdout.write(`Downloaded ${index + 1}/${manifest.length}: ${page.label}\n`);
  }
}

await Promise.all(Array.from({ length: concurrency }, () => worker()));
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

const generatedEntries = manifest
  .map((page) => `  ${JSON.stringify(page.route)}: ${JSON.stringify(page.file)},`)
  .join('\n');
await writeFile(
  generatedMapPath,
  `// Generated by scripts/sync-investor-sidebar-pages.mjs\nexport const investorSidebarPages: Record<string, string> = {\n${generatedEntries}\n};\n`,
  'utf8',
);

console.log(
  `Downloaded ${investingLinks.length} Investing Basics pages and ${generalLinks.length} General Resources pages.`,
);
