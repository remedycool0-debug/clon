import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const referencePath = path.join(
  projectRoot,
  'public',
  'investor-pages',
  'check-out-your-investment-professional.html',
);
const sourceDir = path.join(projectRoot, 'recursos', 'global-menu-pages');
const manifestPath = path.join(projectRoot, 'recursos', 'global-menu-pages.json');
const generatedMapPath = path.join(projectRoot, 'lib', 'investor-global-menu-pages.generated.ts');
const investorOrigin = 'https://www.investor.gov';

function cleanText(value) {
  return value
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#039;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}

function fileNameFor(route) {
  const digest = createHash('sha1').update(route).digest('hex').slice(0, 10);
  const lastSegment = route.split('/').filter(Boolean).at(-1) ?? 'page';
  const safeSegment = lastSegment.replace(/[^a-z0-9-]+/gi, '-').slice(0, 56);
  return `global-${digest}-${safeSegment}`;
}

const html = await readFile(referencePath, 'utf8');
const navStart = html.indexOf('<nav aria-labelledby="block-investor-main-menu-menu"');
const navEnd = html.indexOf('</nav>', navStart);

if (navStart < 0 || navEnd < 0) {
  throw new Error('Could not locate the global navigation in the downloaded Investor.gov HTML.');
}

const globalNavigation = html.slice(navStart, navEnd);
const links = [
  ...globalNavigation.matchAll(/<a\s+[^>]*href="([^"]+)"[^>]*>(.*?)<\/a>/gis),
]
  .map(([, route, label]) => ({
    route: route.replace(/&amp;/g, '&'),
    label: cleanText(label),
  }))
  .filter((link) => link.route.startsWith('/'));

const coreMap = await readFile(path.join(projectRoot, 'lib', 'investor-pages.ts'), 'utf8');
const sidebarManifest = JSON.parse(
  await readFile(path.join(projectRoot, 'recursos', 'sidebar-pages.json'), 'utf8'),
);
const existingRoutes = new Set([
  ...sidebarManifest.map((page) => page.route),
  ...[...coreMap.matchAll(/'(\/[^']+)'\s*:/g)].map((match) => match[1]),
]);
const uniqueLinks = [...new Map(links.map((link) => [link.route, link])).values()].filter(
  (link) => !existingRoutes.has(link.route),
);
const manifest = uniqueLinks.map((link) => ({ ...link, file: fileNameFor(link.route) }));

await mkdir(sourceDir, { recursive: true });

const concurrency = 6;
let nextIndex = 0;

async function worker() {
  while (nextIndex < manifest.length) {
    const index = nextIndex++;
    const page = manifest[index];
    const response = await fetch(new URL(page.route, investorOrigin), {
      headers: { 'user-agent': 'Mozilla/5.0 local-reference-clone' },
    });

    if (!response.ok) {
      throw new Error(`${response.status} ${response.statusText}: ${page.route}`);
    }

    await writeFile(path.join(sourceDir, `${page.file}.html`), await response.text(), 'utf8');
    process.stdout.write(`Downloaded ${index + 1}/${manifest.length}: ${page.label}\n`);
  }
}

await Promise.all(Array.from({ length: concurrency }, () => worker()));
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

const generatedEntries = manifest
  .map((page) => `  ${JSON.stringify(page.route)}: ${JSON.stringify(page.file)},`)
  .join('\n');
await writeFile(
  generatedMapPath,
  `// Generated by scripts/sync-investor-global-menu-pages.mjs\nexport const investorGlobalMenuPages: Record<string, string> = {\n${generatedEntries}\n};\n`,
  'utf8',
);

console.log(`Downloaded ${manifest.length} additional Investor.gov global-menu pages.`);
